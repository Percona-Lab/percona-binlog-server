namespace binsrv {

namespace {

constexpr std::string_view instance_id_file_name{"instance_id"};
constexpr std::string_view tmp_file_suffix{".tmp"};
// An instance id file written by us is 37 bytes (36-char UUID + newline).
// Keep a small, generous upper bound so a hand-edited file is still read.
constexpr std::size_t max_instance_id_file_size{4096U};

[[nodiscard]] std::string
read_existing_instance_id(const std::filesystem::path &instance_id_path) {
  std::error_code is_file_ec;
  if (!std::filesystem::is_regular_file(instance_id_path, is_file_ec)) {
    return {};
  }
  // A file we cannot read or that is larger than expected is treated the same
  // as a spoiled one: the exception is deliberately swallowed and a fresh id
  // is generated by the caller.
  try {
    const auto content{util::read_file_content(
        "instance id file", instance_id_path, max_instance_id_file_size)};
    std::string trimmed{util::as_string_view(content)};
    boost::algorithm::trim(trimmed);
    if (util::is_canonical_uuid(trimmed)) {
      return trimmed;
    }
  } catch (const std::exception &) { // NOLINT(bugprone-empty-catch)
  }
  return {};
}

[[nodiscard]] std::string generate_instance_id() {
  boost::uuids::random_generator generator;
  return boost::uuids::to_string(generator());
}

void persist_instance_id(const std::filesystem::path &instance_id_path,
                         const std::string &instance_id) {
  // Standard write-temp-then-rename idiom (same as the filesystem storage
  // backend): a crash mid-write leaves only the '.tmp' file, never a
  // truncated instance_id. The two fsync calls make the content durable
  // before the rename commits and then make the rename itself durable.
  std::string file_body{instance_id};
  file_body += '\n';

  auto tmp_path{instance_id_path};
  tmp_path += tmp_file_suffix;

  util::write_file_content("instance id tmp file", tmp_path,
                           util::as_const_byte_span(file_body));
  util::fsync(tmp_path);

  std::error_code rename_ec;
  std::filesystem::rename(tmp_path, instance_id_path, rename_ec);
  if (rename_ec) {
    util::exception_location().raise<std::runtime_error>(
        "cannot rename instance id tmp file: " + rename_ec.message());
  }
  util::fsync(instance_id_path.parent_path());
}

} // anonymous namespace

std::string
load_or_create_instance_id(const std::filesystem::path &local_settings_path) {
  const auto instance_id_path{local_settings_path / instance_id_file_name};

  auto existing{read_existing_instance_id(instance_id_path)};
  if (!existing.empty()) {
    return existing;
  }

  auto generated{generate_instance_id()};
  persist_instance_id(instance_id_path, generated);
  return generated;
}

} // namespace binsrv
